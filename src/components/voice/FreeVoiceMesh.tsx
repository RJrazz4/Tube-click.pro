import { useEffect, useRef, useState } from "react";
import { Download, Loader2, Network, Play, Users } from "lucide-react";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { Button } from "@/components/ui/button";
import { Textarea } from "@/components/ui/textarea";
import { Label } from "@/components/ui/label";
import {
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from "@/components/ui/select";
import { KOKORO_VOICES, kokoroEngine } from "@/lib/p2p/kokoroEngine";
import { VoiceMesh, type MeshProgress } from "@/lib/p2p/voiceMesh";

/**
 * Free Voice — P2P Turbo panel on the Voiceover page.
 *
 * Unlimited English voiceover generated by Kokoro in the browser.
 * When other creators are online with "share this device" on, script
 * chunks are generated in parallel on their browsers too (WebRTC) and
 * stitched here — with zero peers it simply generates locally.
 */
export default function FreeVoiceMesh() {
  const [script, setScript] = useState("");
  const [voice, setVoice] = useState(KOKORO_VOICES[0].id);
  const [shareDevice, setShareDevice] = useState(false);
  const [peers, setPeers] = useState(0);
  const [meshState, setMeshState] = useState<"connecting" | "connected" | "local-only">("connecting");
  const [modelState, setModelState] = useState<"cold" | "loading" | "ready" | "error">("cold");
  const [busy, setBusy] = useState(false);
  const [progress, setProgress] = useState<MeshProgress | null>(null);
  const [error, setError] = useState("");
  const [resultUrl, setResultUrl] = useState("");
  const meshRef = useRef<VoiceMesh | null>(null);

  useEffect(() => {
    const signalingUrl =
      (import.meta as unknown as { env?: Record<string, string> }).env?.VITE_P2P_SIGNALING_URL || "";
    const mesh = new VoiceMesh(kokoroEngine, {
      signalingUrl,
      events: {
        onPeers: (n) => setPeers(n),
        onStatus: (s) => setMeshState(s === "connected" ? "connected" : "local-only"),
      },
    });
    meshRef.current = mesh;
    void mesh.connect();
    return () => mesh.close();
  }, []);

  const warmModel = async () => {
    if (modelState === "ready" || modelState === "loading") return;
    setModelState("loading");
    try {
      await kokoroEngine.warmup();
      setModelState("ready");
    } catch {
      setModelState("error");
    }
  };

  const toggleShare = (on: boolean) => {
    setShareDevice(on);
    meshRef.current?.setWorkerEnabled(on);
    if (on) void warmModel();
  };

  const generate = async () => {
    const mesh = meshRef.current;
    if (!mesh || !script.trim() || busy) return;
    setBusy(true);
    setError("");
    setResultUrl("");
    setProgress(null);
    try {
      await warmModel();
      const blob = await mesh.generate(script.trim(), voice, (p) => setProgress(p));
      setResultUrl(URL.createObjectURL(blob));
    } catch (e) {
      setError(e instanceof Error ? e.message : "Generation failed on this device.");
    } finally {
      setBusy(false);
    }
  };

  return (
    <Card className="cyber-card border-border mt-6">
      <CardHeader className="pb-3">
        <CardTitle className="font-display text-base text-foreground flex items-center gap-2">
          <Network className="w-4 h-4 text-primary" />
          Free Voice — P2P Turbo
          <span className="ml-auto inline-flex items-center gap-1.5 text-xs font-normal text-muted-foreground">
            <Users className="w-3.5 h-3.5" />
            {meshState === "connected" ? `${peers} creator${peers === 1 ? "" : "s"} online to help` : "Local mode"}
          </span>
        </CardTitle>
      </CardHeader>
      <CardContent className="space-y-4">
        <p className="text-xs text-muted-foreground leading-relaxed">
          Unlimited English voiceover, generated by an AI voice model that runs in the browser —
          no server, no per-use cost. With Turbo sharing on, your script is split into small
          chunks and generated in parallel on other online creators' browsers and yours, then
          stitched into one file. Only script text travels to a peer — never your audio files.
          First use downloads the voice model once (~115 MB), then it stays cached.
        </p>

        <div className="space-y-1.5">
          <Label className="text-sm text-foreground">Voice</Label>
          <Select value={voice} onValueChange={setVoice}>
            <SelectTrigger className="bg-secondary border-border h-10 text-sm">
              <SelectValue placeholder="Select a voice" />
            </SelectTrigger>
            <SelectContent className="bg-card border-border max-h-[300px]">
              {KOKORO_VOICES.map((v) => (
                <SelectItem key={v.id} value={v.id}>
                  <span className="text-xs">{v.name}</span>
                </SelectItem>
              ))}
            </SelectContent>
          </Select>
        </div>

        <Textarea
          value={script}
          onChange={(e) => setScript(e.target.value)}
          placeholder="Write or paste your English voiceover script…"
          className="min-h-[140px] bg-secondary border-border resize-none text-sm"
        />
        <div className="flex items-center justify-between text-xs text-muted-foreground">
          <span>{script.length} characters</span>
          <span>{modelState === "ready" ? "Voice model ready" : modelState === "loading" ? "Loading voice model…" : modelState === "error" ? "Model failed to load — check connection" : "Model loads on first use"}</span>
        </div>

        <label className="flex cursor-pointer items-start gap-3 rounded-xl bg-secondary/50 p-3">
          <input
            type="checkbox"
            checked={shareDevice}
            onChange={(e) => toggleShare(e.target.checked)}
            className="mt-0.5 h-4 w-4 accent-fuchsia-500"
          />
          <span className="text-xs leading-relaxed text-muted-foreground">
            <span className="font-semibold text-foreground">Share this device (Turbo).</span>{" "}
            While this tab is open, your browser can also generate chunks for other creators —
            and theirs speed up yours. Turn it off any time.
          </span>
        </label>

        <div className="flex items-center justify-center gap-3">
          <Button onClick={generate} disabled={busy || !script.trim()} className="cyber-button rounded-full px-6">
            {busy ? <Loader2 className="w-4 h-4 mr-2 animate-spin" /> : <Play className="w-4 h-4 mr-2" />}
            {busy ? "Generating…" : "Generate free voiceover"}
          </Button>
          {resultUrl && (
            <Button
              variant="outline"
              onClick={() => {
                const a = document.createElement("a");
                a.href = resultUrl;
                a.download = "tubeclick-free-voice.wav";
                a.click();
              }}
              className="rounded-full border-border"
            >
              <Download className="w-4 h-4 mr-2" /> Download WAV
            </Button>
          )}
        </div>

        {progress && busy && (
          <p className="text-center text-xs text-muted-foreground">
            {progress.done}/{progress.total} parts done — {progress.viaPeers} via creators, {progress.viaLocal} on this device
          </p>
        )}
        {error && <p className="text-center text-xs text-red-300">{error}</p>}
        {resultUrl && <audio controls src={resultUrl} className="w-full" />}
      </CardContent>
    </Card>
  );
}
